import concurrent.futures
import importlib.util
import os
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'scripts'))
import sandbox


class EnvironmentTests(unittest.TestCase):
    def test_repeat_preserves_bytes_and_permissions(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / '.env'
            first = sandbox.ensure_env(path)
            before = path.read_bytes()
            self.assertEqual(first, sandbox.ensure_env(path))
            self.assertEqual(before, path.read_bytes())
            self.assertEqual(path.stat().st_mode & 0o777, 0o600)
            self.assertEqual(len(first['SUPERUSER_API_KEY']), 12)
            self.assertEqual(len(first['SUPERUSER_API_TOKEN']), 40)

    def test_partial_config_fails_without_rotation(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / '.env'
            path.write_text('SECRET_KEY=keep\n')
            with self.assertRaises(ValueError):
                sandbox.ensure_env(path)
            self.assertEqual(path.read_text(), 'SECRET_KEY=keep\n')

    def test_config_is_data(self):
        for value in ['KEY=$(touch /tmp/bad)', 'KEY=`id`', 'bad data', 'KEY=a\nKEY=b']:
            with self.assertRaises(ValueError):
                sandbox.parse_env(value)

    def test_atomic_concurrent_initialization(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / '.env'
            with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
                values = list(pool.map(lambda _: sandbox.ensure_env(path), range(4)))
            self.assertTrue(all(v == values[0] for v in values))

    def test_project_cannot_be_overridden(self):
        with self.assertRaises(ValueError):
            sandbox.validate_env(dict(sandbox.new_env(), COMPOSE_PROJECT_NAME='netbox'))

    def test_explicit_compose_target(self):
        command = sandbox.compose_argv(['up', '-d'])
        self.assertIn(sandbox.PROJECT, command)
        self.assertIn(str(sandbox.ROOT / 'docker-compose.yml'), command)
        self.assertIn(str(sandbox.ROOT / '.env'), command)
        with self.assertRaises(ValueError):
            sandbox.compose_argv(['-p', 'other', 'down'])

    def test_generation_uses_direct_interpreter(self):
        with mock.patch.object(sandbox, 'run', return_value='') as run:
            sandbox.django(['makemigrations', 'netbox_custom_field_profiles', '--noinput'], oneoff=True)
        args = run.call_args.args[0]
        self.assertEqual(args[:6], ['run', '--rm', '--no-deps', '--entrypoint', sandbox.PYTHON, 'netbox'])
        self.assertNotIn('/opt/netbox/docker-entrypoint.sh', args)
        self.assertIn(sandbox.MANAGE, args)

    def test_uncorrected_migration_prevents_bootstrap(self):
        with mock.patch.object(sandbox, 'ensure_env'), mock.patch.object(sandbox.Path, 'read_text', return_value='handwritten'), mock.patch.object(sandbox, 'run') as run:
            with self.assertRaises(ValueError):
                sandbox.setup()
            run.assert_not_called()

    def test_generation_failure_never_starts_web(self):
        events = []
        with mock.patch.object(sandbox, 'ensure_env'), mock.patch.object(sandbox, 'validate_compose'), mock.patch.object(sandbox.Path, 'read_text', return_value='handwritten'), mock.patch.object(sandbox.Path, 'read_bytes', return_value=b'handwritten'), mock.patch.object(sandbox.Path, 'unlink'), mock.patch.object(sandbox.Path, 'exists', return_value=False), mock.patch.object(sandbox.Path, 'write_bytes'), mock.patch.object(sandbox, 'run', side_effect=lambda args, **kw: events.append(args)), mock.patch.object(sandbox, 'django', side_effect=['PRE_BOOTSTRAP_SCHEMA_ABSENT', RuntimeError('generation failed')]):
            with self.assertRaises(RuntimeError):
                sandbox.prepare_schema()
        self.assertEqual(events[0], ['build'])
        self.assertEqual(events[1][-3:], ['postgres', 'redis', 'redis-cache'])
        self.assertEqual(len(events), 2)

    def test_no_public_or_external_resources(self):
        import json
        bad = [
            {'name': sandbox.PROJECT, 'volumes': {'db': {'external': True}}, 'services': {}},
            {'name': sandbox.PROJECT, 'services': {'postgres': {'ports': [{'host_ip': '0.0.0.0', 'target': 5432}]}}},
        ]
        for config in bad:
            with mock.patch.object(sandbox, 'run', return_value=json.dumps(config)):
                with self.assertRaises(ValueError):
                    sandbox.validate_compose()

    def test_normal_startup_follows_healthy_dependencies(self):
        events = []
        with mock.patch.object(sandbox, 'ensure_env'), mock.patch.object(sandbox, 'validate_compose'), mock.patch.object(sandbox.Path, 'read_text', return_value='# Generated by Django'), mock.patch.object(sandbox, 'run', side_effect=lambda args, **kw: events.append(args)), mock.patch.object(sandbox, 'runtime', side_effect=lambda: events.append(['runtime'])), mock.patch.object(sandbox, 'seed', side_effect=lambda: events.append(['seed'])):
            sandbox.setup()
        self.assertEqual(events[0], ['build'])
        self.assertEqual(events[1][-3:], ['postgres', 'redis', 'redis-cache'])
        self.assertEqual(events[2], ['up', '-d', '--wait', '--wait-timeout', '600'])
        self.assertEqual(events[3], ['runtime'])
        self.assertEqual(events[4], ['seed'])


if __name__ == '__main__':
    unittest.main()
